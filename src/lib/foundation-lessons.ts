export type Mascot = 'penguin' | 'panda' | 'pero'

export type Quiz = {
  context?: string
  question: string
  options: string[]
  correct: number
  feedback: string
}

export type RuleBlock = {
  title: string
  mascot: Mascot
  lead: string
  body: Array<string | { speaker: Mascot; text: string } | { table: { headers: string[]; rows: string[][] } }>
  examples: string[]
  /** Скороговорка: played back slowly, then normally, then fast. */
  tongueTwister?: {
    ru: string
    uz: string
    breakdown?: Array<{ word: string; transcription: string; sound: string }>
  }
}

export type Phrase = {
  ru: string
  uz: string
  pronunciation?: string
  example: string
  icon: string
}

export type Vocab = {
  ru: string
  uz: string
  example: string
  icon: string
}

